// Discovers SVG assets and generates the TypeScript registry.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parsePartSvg } from "./svg-check.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const NAME_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const HEX_RE = /^#[0-9a-f]{6}$/;

function fail(msg) {
    throw new Error(`[registry] ${msg}`);
}

function readManifest(assetsDir) {
    const file = join(assetsDir, "manifest.json");
    if (!existsSync(file)) fail(`manifest not found: ${file}`);
    let m;
    try {
        m = JSON.parse(readFileSync(file, "utf8"));
    } catch (e) {
        fail(`invalid manifest.json (JSON): ${e.message}`);
    }
    const { canvas, layers, palettes } = m;
    if (!canvas || !(canvas.width > 0) || !(canvas.height > 0))
        fail("manifest.canvas.width/height required (> 0)");
    if (!Array.isArray(layers) || layers.length === 0)
        fail("manifest.layers must be a non-empty array");
    const seen = new Set();
    for (const l of layers) {
        if (!l || !NAME_RE.test(l.name ?? ""))
            fail(`invalid layer name: ${JSON.stringify(l?.name)}`);
        if (seen.has(l.name)) fail(`layer declared twice: ${l.name}`);
        seen.add(l.name);
        if (l.probability !== undefined && !(l.probability >= 0 && l.probability <= 100)) {
            fail(`layer ${l.name}: probability must be between 0 and 100`);
        }
    }
    if (!palettes || typeof palettes !== "object") fail("manifest.palettes required (object)");
    for (const [k, list] of Object.entries(palettes)) {
        if (!Array.isArray(list) || list.length === 0)
            fail(`palette ${k}: non-empty array required`);
        for (const c of list)
            if (!HEX_RE.test(c))
                fail(`palette ${k}: invalid color ${JSON.stringify(c)} (expected #rrggbb)`);
    }
    return { canvas, layers, palettes };
}

/** Builds the in-memory registry from an assets directory. */
export function buildRegistry(assetsDir = join(root, "assets")) {
    const { canvas, layers, palettes } = readManifest(assetsDir);
    const tokens = Object.keys(palettes);

    const dirs = readdirSync(assetsDir).filter((n) => statSync(join(assetsDir, n)).isDirectory());
    for (const d of dirs) {
        if (!layers.some((l) => l.name === d))
            fail(`the assets/${d} folder is not declared in manifest.layers`);
    }

    const parts = {};
    for (const { name: layer } of layers) {
        const dir = join(assetsDir, layer);
        if (!existsSync(dir)) fail(`missing folder for layer "${layer}": ${dir}`);
        parts[layer] = {};
        const files = readdirSync(dir)
            .filter((f) => !f.startsWith("."))
            .toSorted();
        for (const f of files) {
            if (!f.endsWith(".svg")) fail(`${layer}/${f}: only .svg files are accepted`);
            const name = f.slice(0, -4);
            if (!NAME_RE.test(name))
                fail(
                    `${layer}/${f}: invalid name (kebab-case expected: lowercase letters, digits, hyphens)`
                );
            try {
                parts[layer][name] = parsePartSvg(readFileSync(join(dir, f), "utf8"), tokens).inner;
            } catch (e) {
                fail(`${layer}/${f}: ${e.message}`);
            }
        }
    }
    return { canvas, layers, palettes, parts };
}

/** Exact content of the generated TypeScript module (pure: allows checking without writing). */
export function renderRegistry(registry) {
    return (
        `// GENERATED by scripts/build-registry.mjs — do not edit by hand.\n` +
        `import type { Registry } from "./types.js";\n\n` +
        `export const REGISTRY: Registry = ${JSON.stringify(registry, null, 1)};\n`
    );
}

export function writeRegistry(registry, outFile) {
    writeFileSync(outFile, renderRegistry(registry));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    try {
        writeRegistry(buildRegistry(), join(root, "registry.generated.ts"));
    } catch (e) {
        process.stderr.write(`${e.message}\n`);
        process.exit(1);
    }
}
