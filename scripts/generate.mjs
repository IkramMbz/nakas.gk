// Generates TypeScript modules derived from sources (avatar registry, skills, CSS).
//   node scripts/generate.mjs           write files
//   node scripts/generate.mjs --check   fail if a committed file is stale (CI)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

import { buildRegistry, renderRegistry } from "../src/avatars/scripts/build-registry.mjs";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const check = process.argv.includes("--check");
const stale = [];

/** Writes `content` to `file`, or reports drift in --check mode. */
function emit(file, content, { committed }) {
    const path = join(root, file);
    const current = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (current === content) return;
    if (!check) writeFileSync(path, content);
    else if (committed) stale.push(file);
}

// 1. Avatar registry (SVG → TypeScript).
emit("src/avatars/registry.generated.ts", renderRegistry(buildRegistry()), { committed: true });

// 2. Skills: every SKILL.md, keyed by the `name:` in its front matter.
const SKILL_ROOTS = ["src/devkit/agents", "src/agents"];
const skills = {};
for (const base of SKILL_ROOTS) {
    for (const dir of readdirSync(join(root, base), { withFileTypes: true })) {
        const file = join(root, base, dir.name, "SKILL.md");
        if (!dir.isDirectory() || !existsSync(file)) continue;
        const text = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
        const name = /^---\n(?:[^\n]*\n)*?name:\s*(\S+)\s*\n/.exec(text)?.[1];
        if (!name)
            throw new Error(`${base}/${dir.name}/SKILL.md : « name: » absent du front matter`);
        if (name in skills) throw new Error(`Skill « ${name} » défini deux fois`);
        skills[name] = text;
    }
}
const sorted = Object.fromEntries(Object.entries(skills).toSorted(([a], [b]) => (a < b ? -1 : 1)));
emit(
    "src/agents/skills.generated.ts",
    `// GENERATED by scripts/generate.mjs from every SKILL.md — do not edit by hand.\n` +
        `export const SKILLS: Readonly<Record<string, string>> = ${JSON.stringify(sorted, null, 4)};\n`,
    { committed: true }
);

// 3. CSS: minified bundle embedded as a string (injected into the shadow DOM, no host-side CSS import).
const css = await build({
    entryPoints: [join(root, "src/styles/index.css")],
    bundle: true,
    minify: true,
    write: false,
    logLevel: "silent"
});
const text = css.outputFiles[0]?.text ?? "";
emit(
    "src/ui/styles.generated.ts",
    `// GENERATED by scripts/generate.mjs from src/styles — do not edit by hand.\nexport const STYLES = ${JSON.stringify(text)};\n`,
    { committed: false }
);

if (stale.length > 0) {
    process.stderr.write(
        `Fichiers générés périmés : ${stale.join(", ")}\nLance : pnpm run generate\n`
    );
    process.exit(1);
}
